'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const native=new Map(),events={};let next=0;
const motion={matches:false,addEventListener:(_,fn)=>{events.motion=fn;}};
const document={hidden:false,addEventListener:(name,fn)=>{events[name]=fn;}};
const context=vm.createContext({document,window:{matchMedia:()=>motion,addEventListener:(name,fn)=>{events[name]=fn;}},
  requestAnimationFrame:fn=>{const id=++next;native.set(id,fn);return id;},cancelAnimationFrame:id=>native.delete(id)});
vm.runInContext(fs.readFileSync('js/flame.js','utf8'),context);
const fire=vm.runInContext('FlameCompass',context),frames=fire.frames;
let calls=0;
const a=frames.request(()=>{calls++;frames.request(()=>calls++);});
frames.request(()=>{throw new Error('decorative failure');});
const b=frames.request(()=>calls++);
assert.equal(native.size,1,'all visual callbacks share one native frame');
frames.cancel(b);
let [id,callback]=native.entries().next().value;native.delete(id);callback(100);
assert.equal(calls,1);assert.equal(native.size,1,'next frame scheduled once even after a callback throws');
document.hidden=true;events.visibilitychange();assert.equal(native.size,0);
assert.equal(frames.state().queued,1,'paused work retained until visible');
document.hidden=false;events.visibilitychange();assert.equal(native.size,1);
motion.matches=true;events.motion();assert.equal(native.size,0);
motion.matches=false;events.motion();assert.equal(native.size,1);
[id,callback]=native.entries().next().value;native.delete(id);callback(200);
assert.equal(calls,2);assert.equal(native.size,0);
frames.cancel(a);fire.mountAll({});fire.destroyAll();fire.destroyAll();
frames.request(()=>calls++);events.pagehide();assert.equal(native.size,0);assert.equal(frames.state().queued,0);
console.log('flame shared RAF / cancellation / visibility / reduced motion / failure isolation / pagehide: PASS');
