'use strict';
// UUID manifest is committed. Reordering a bank preserves IDs; a renamed topic is a new topic.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),{randomUUID}=require('node:crypto');
const root=path.resolve(__dirname,'..'),manifest=path.join(root,'backend/data/topics.json');
const old=fs.existsSync(manifest)?JSON.parse(fs.readFileSync(manifest,'utf8')):[];
const ctx=vm.createContext({console});ctx.window=ctx;
for(const f of ['vocab','banks'])vm.runInContext(fs.readFileSync(path.join(root,'demo/js/'+f+'.js'),'utf8'),ctx);
const banks=vm.runInContext('BUILTIN_BANKS',ctx),ids={},topics=[];
for(const bank of banks){ids[bank.id]={};const parsed=ctx.VocabParser.parseVocabMarkdown(bank.md);if(!parsed.ok)throw Error(bank.name);
  for(const t of parsed.terms){const prior=old.find(x=>x.vocab_id===bank.id&&x.title===t.title);const id=prior?.id||randomUUID();ids[bank.id][t.title]=id;topics.push({id,vocab_id:bank.id,title:t.title,domain:bank.name,level:t.level});}
}
fs.mkdirSync(path.dirname(manifest),{recursive:true});fs.writeFileSync(manifest,JSON.stringify(topics,null,2)+'\n');
fs.writeFileSync(path.join(root,'demo/js/topic-ids.js'),'// Generated by scripts/sync-topics.cjs; keep committed UUIDs.\nconst BUILTIN_TOPIC_IDS = '+JSON.stringify(ids,null,2)+';\n');
console.log('Stable topic manifest:',topics.length);
